using DeValpo.MediaIntelligence.Api.Auth;
using DeValpo.MediaIntelligence.Api.Audit;
using DeValpo.MediaIntelligence.Application.Audit;
using DeValpo.MediaIntelligence.Application.AnalysisJobs;
using DeValpo.MediaIntelligence.Application.MediaAnalysis;
using DeValpo.MediaIntelligence.Contracts;
using DeValpo.MediaIntelligence.Contracts.AnalysisJobs;
using DeValpo.MediaIntelligence.Contracts.AnalysisResults;
using Microsoft.AspNetCore.Mvc;

namespace DeValpo.MediaIntelligence.Api.Controllers;

[ApiController]
[Route("api/v1/analysis-jobs")]
public sealed class AnalysisJobsController(
    IAnalysisJobApplicationService jobService,
    IRequestClientAccessService accessService,
    IMediaAnalysisApplicationService analysisService,
    IAuditApplicationService auditService) : ControllerBase
{
    /// <summary>
    /// Creates a pending analysis job without uploading media.
    /// </summary>
    /// <remarks>
    /// Creates a job shell for clients that need to track or reserve work before submitting media.
    /// </remarks>
    /// <param name="request">Job creation data with client, profile and asset type.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <response code="201">Returns the created job identifier and initial status.</response>
    /// <response code="400">The request is invalid or references an unsupported profile.</response>
    /// <response code="401">A valid bearer token was not provided.</response>
    /// <response code="403">The token cannot create work for the requested client or profile.</response>
    [HttpPost]
    [ProducesResponseType(typeof(CreateAnalysisJobResponse), StatusCodes.Status201Created)]
    [ProducesResponseType(typeof(ApiErrorResponse), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> Create(
        [FromBody] CreateAnalysisJobRequest request,
        CancellationToken cancellationToken)
    {
        if (!await accessService.CanSubmitAsync(User, request.ClientKey, request.ProfileKey, cancellationToken))
        {
            return Forbid();
        }

        var response = await jobService.CreateAsync(request, cancellationToken);
        return CreatedAtAction(nameof(GetById), new { jobId = response.JobId }, response);
    }

    /// <summary>
    /// Returns job metadata and status for the requested job.
    /// </summary>
    /// <remarks>
    /// Use this endpoint to inspect job state, timestamps and terminal error information.
    /// </remarks>
    /// <param name="jobId">Analysis job identifier.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <response code="200">Returns the job metadata and current status.</response>
    /// <response code="401">A valid bearer token was not provided.</response>
    /// <response code="404">No job exists with the provided identifier.</response>
    [HttpGet("{jobId:guid}")]
    [ProducesResponseType(typeof(AnalysisJobResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetById(Guid jobId, CancellationToken cancellationToken)
    {
        var response = await jobService.GetByIdAsync(jobId, cancellationToken);
        if (response is null || !accessService.CanAccessClientResource(User, response.ClientKey))
        {
            return NotFound();
        }

        return Ok(response);
    }

    /// <summary>
    /// Returns the persisted analysis result for a completed job.
    /// </summary>
    /// <remarks>
    /// Returns the stored output generated by the analysis pipeline after the job has produced a result.
    /// </remarks>
    /// <param name="jobId">Analysis job identifier.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <response code="200">Returns the persisted analysis result.</response>
    /// <response code="401">A valid bearer token was not provided.</response>
    /// <response code="404">The job or result was not found.</response>
    [HttpGet("{jobId:guid}/result")]
    [ProducesResponseType(typeof(AnalysisResultResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetResult(Guid jobId, CancellationToken cancellationToken)
    {
        var job = await jobService.GetByIdAsync(jobId, cancellationToken);
        if (job is null || !accessService.CanAccessClientResource(User, job.ClientKey))
        {
            return NotFound();
        }

        var response = await analysisService.GetResultAsync(jobId, cancellationToken);
        await auditService.RecordAsync(
            AuditRequestFactory.Create(
                User,
                AuditEventTypes.AnalysisResultRead,
                "AnalysisJob",
                jobId.ToString(),
                job.ClientKey,
                response is null ? AuditOutcome.Failed : AuditOutcome.Success,
                new Dictionary<string, string> { ["resultFound"] = (response is not null).ToString() }),
            cancellationToken);
        return response is null ? NotFound() : Ok(response);
    }

    /// <summary>
    /// Cancels a non-terminal analysis job.
    /// </summary>
    /// <remarks>
    /// Marks a pending or running job as cancelled. Completed and failed jobs cannot be cancelled.
    /// </remarks>
    /// <param name="jobId">Analysis job identifier.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <response code="204">The job was cancelled.</response>
    /// <response code="400">The job cannot be cancelled from its current status.</response>
    /// <response code="401">A valid bearer token was not provided.</response>
    /// <response code="404">The job was not found or is not owned by the authenticated client.</response>
    [HttpPost("{jobId:guid}/cancel")]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(typeof(ApiErrorResponse), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> Cancel(Guid jobId, CancellationToken cancellationToken)
    {
        var job = await jobService.GetByIdAsync(jobId, cancellationToken);
        if (job is null || !accessService.CanAccessClientResource(User, job.ClientKey))
        {
            return NotFound();
        }

        await jobService.CancelAsync(jobId, cancellationToken);
        return NoContent();
    }
}
